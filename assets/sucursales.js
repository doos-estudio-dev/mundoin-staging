function onSelect(ev) {
  const container = document.getElementById("info-sucursal-container");
  const tourContainer = document.getElementById("tour-container");
  const tourLink = document.getElementById("tour-link");
  container.classList.remove("twl-hidden");
  const l1 = document.getElementById("label-1");
  const l2 = document.getElementById("label-2");
  const l3 = document.getElementById("label-3");
  const name = document.getElementById("name-sucursal");
  const direccion = document.getElementById("sucursal-direccion");
  const horario = document.getElementById("sucursal-horario");
  const contacto = document.getElementById("sucursal-contacto");
  const map = document.getElementById("sucursal-map");
  const shop = data[ev.id];
  name.innerText = `Sucursal ${shop.nombre}`;
  direccion.innerText = shop.direccion;
  contacto.innerText = shop.contacto;
  horario.innerText = shop.horario;
  map.innerHTML = shop.map;
  l1.style = `--_img: url(${shop.imgs[0]})`;
  l2.style = `--_img: url(${shop.imgs[1]})`;
  l3.style = `--_img: url(${shop.imgs[2]})`;
  if (shop.recorrido) {
    tourContainer.style.display = "flex";
    tourLink.href = shop.recorrido;
  } else {
    tourContainer.style.display = "none";
    tourLink.href = "#";
  }
}

function onScrollX(ev) {
  const sucursalesContainer = document.getElementById("sucursales-container");
  const positionX = sucursalesContainer.scrollLeft;
  if (ev.id === "r") {
    sucursalesContainer.scrollLeft += 300;
  } else {
    positionX === 0
      ? (sucursalesContainer.scrollLeft = 2200)
      : (sucursalesContainer.scrollLeft -= 300);
  }
}
